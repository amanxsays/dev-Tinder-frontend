package com.amanxsays.devtinder.platform;

import android.graphics.Paint;
import android.graphics.pdf.PdfDocument;
import android.view.View;
import android.view.ViewGroup;
import android.widget.Button;
import android.widget.TextView;
import androidx.test.core.app.ActivityScenario;
import androidx.test.ext.junit.runners.AndroidJUnit4;
import com.amanxsays.devtinder.MainActivity;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.net.HttpURLConnection;
import java.net.URL;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.Test;
import org.junit.runner.RunWith;
import static org.junit.Assert.*;

/** Real Android PDF renderer with local generated bytes; never fetches a personal resume. */
@RunWith(AndroidJUnit4.class)
public class PdfPreviewTest {
    private static final String URL_VALUE = "https://res.cloudinary.com/fixture/raw/upload/sample.pdf";
    private static class Response extends HttpURLConnection {
        final byte[] bytes;
        Response(URL url, byte[] bytes) { super(url); this.bytes = bytes; }
        @Override public void connect() {}
        @Override public void disconnect() {}
        @Override public boolean usingProxy() { return false; }
        @Override public int getResponseCode() { return 200; }
        @Override public String getContentType() { return "application/pdf"; }
        @Override public long getContentLengthLong() { return bytes.length; }
        @Override public InputStream getInputStream() { return new ByteArrayInputStream(bytes); }
    }
    private byte[] pdf() throws Exception {
        PdfDocument document = new PdfDocument();
        try (ByteArrayOutputStream bytes = new ByteArrayOutputStream()) {
            for (int i = 1; i <= 2; i++) {
                PdfDocument.Page page = document.startPage(new PdfDocument.PageInfo.Builder(300, 400, i).create());
                Paint paint = new Paint(); paint.setTextSize(18);
                page.getCanvas().drawText("DevTinder fixture " + i, 24, 48, paint);
                document.finishPage(page);
            }
            document.writeTo(bytes); return bytes.toByteArray();
        } finally { document.close(); }
    }
    private TextView text(View view, String prefix) {
        if (view instanceof TextView && ((TextView) view).getText().toString().startsWith(prefix)) return (TextView) view;
        if (view instanceof ViewGroup) {
            ViewGroup group = (ViewGroup) view;
            for (int i = 0; i < group.getChildCount(); i++) { TextView result = text(group.getChildAt(i), prefix); if (result != null) return result; }
        }
        return null;
    }
    private void awaitText(ActivityScenario<MainActivity> scenario, AtomicReference<PdfPreviewDialog> dialog, String prefix) throws Exception {
        for (int i = 0; i < 100; i++) {
            AtomicBoolean found = new AtomicBoolean();
            scenario.onActivity(activity -> found.set(text(dialog.get().getWindow().getDecorView(), prefix) != null));
            if (found.get()) return;
            Thread.sleep(100);
        }
        fail("PDF did not reach expected state: " + prefix);
    }
    @Test public void generatedPdfRendersNavigatesZoomsAndCleansPrivateCache() throws Exception {
        byte[] bytes = pdf(); ExecutorService worker = Executors.newSingleThreadExecutor();
        AtomicReference<PdfPreviewDialog> dialog = new AtomicReference<>(); AtomicBoolean closed = new AtomicBoolean();
        try (ActivityScenario<MainActivity> scenario = ActivityScenario.launch(MainActivity.class)) {
            scenario.onActivity(activity -> {
                PdfPreviewDialog preview = new PdfPreviewDialog(activity, worker, URL_VALUE, "Fixture.pdf", () -> closed.set(true), url -> new Response(url, bytes));
                dialog.set(preview); preview.show();
            });
            awaitText(scenario, dialog, "Page 1 of 2");
            scenario.onActivity(activity -> ((Button) text(dialog.get().getWindow().getDecorView(), "Next")).performClick());
            awaitText(scenario, dialog, "Page 2 of 2");
            scenario.onActivity(activity -> ((Button) text(dialog.get().getWindow().getDecorView(), "+")).performClick());
            awaitText(scenario, dialog, "Page 2 of 2 · 150%");
            scenario.onActivity(activity -> dialog.get().dismiss());
            assertTrue(closed.get());
            worker.shutdown(); assertTrue(worker.awaitTermination(10, TimeUnit.SECONDS));
            scenario.onActivity(activity -> {
                java.io.File[] files = activity.getCacheDir().listFiles((folder, name) -> name.startsWith("devtinder-resume-") && name.endsWith(".pdf"));
                assertNotNull(files); assertEquals(0, files.length);
            });
        } finally { worker.shutdownNow(); }
    }
    @Test public void redirectOutsideAllowedResumeHostIsNeverRequested() throws Exception {
        ExecutorService worker = Executors.newSingleThreadExecutor(); AtomicInteger requests = new AtomicInteger();
        AtomicReference<PdfPreviewDialog> dialog = new AtomicReference<>();
        try (ActivityScenario<MainActivity> scenario = ActivityScenario.launch(MainActivity.class)) {
            scenario.onActivity(activity -> {
                PdfPreviewDialog preview = new PdfPreviewDialog(activity, worker, URL_VALUE, "Fixture.pdf", () -> {}, url -> {
                    requests.incrementAndGet(); return new Response(url, new byte[0]) {
                        @Override public int getResponseCode() { return 302; }
                        @Override public String getHeaderField(String name) { return "https://untrusted.invalid/resume.pdf"; }
                    };
                }); dialog.set(preview); preview.show();
            });
            awaitText(scenario, dialog, "This PDF could not be displayed");
            assertEquals(1, requests.get()); scenario.onActivity(activity -> dialog.get().dismiss());
        } finally { worker.shutdown(); worker.awaitTermination(10, TimeUnit.SECONDS); }
    }
    @Test public void oversizedResponseIsRejectedBeforeReadingBody() throws Exception {
        ExecutorService worker = Executors.newSingleThreadExecutor(); AtomicBoolean read = new AtomicBoolean();
        AtomicReference<PdfPreviewDialog> dialog = new AtomicReference<>();
        try (ActivityScenario<MainActivity> scenario = ActivityScenario.launch(MainActivity.class)) {
            scenario.onActivity(activity -> {
                PdfPreviewDialog preview = new PdfPreviewDialog(activity, worker, URL_VALUE, "Fixture.pdf", () -> {}, url -> new Response(url, new byte[0]) {
                    @Override public long getContentLengthLong() { return 5L * 1024 * 1024 + 1; }
                    @Override public InputStream getInputStream() { read.set(true); return new ByteArrayInputStream(new byte[0]); }
                }); dialog.set(preview); preview.show();
            });
            awaitText(scenario, dialog, "This PDF could not be displayed");
            assertFalse(read.get()); scenario.onActivity(activity -> dialog.get().dismiss());
        } finally { worker.shutdown(); worker.awaitTermination(10, TimeUnit.SECONDS); }
    }
}
